def _build_generate_item_prompt(
    kind: str, subject: str, project_context: str, parent_context: str, previous_draft: Optional[dict] = None
) -> str:
    kind_label = {
        "epic": "an epic",
        "story": "a user story",
        "acceptance_criterion": "an acceptance criterion",
        "scenario": "a Given/When/Then scenario",
        "error_handling": "an error-handling entry",
    }[kind]
    parts = [
        f"A project manager wants to add {kind_label} with this subject/description:\n\n{subject}\n\n",
    ]
    if project_context:
        parts.append(f"Here is a condensed summary of this project's existing epics and stories, for context:\n\n{project_context}\n\n")
    if parent_context:
        parts.append(f"Here is the specific context this new item belongs under:\n\n{parent_context}\n\n")
    if previous_draft:
        parts.append(
            "The PM regenerated instead of accepting this previous draft — they want a "
            "meaningfully different take, not a light rewording of it. Change the actual "
            "approach (different emphasis, structure, or specific mechanics), not just a "
            "few words:\n\n"
            f"{json.dumps(previous_draft, indent=2)}\n\n"
        )
    if kind == "epic":
        parts.append(
            "Produce a short, imperative epic title, plus any assumptions or dependencies "
            "that are clearly implied by what the PM wrote (leave both empty rather than "
            "inventing generic ones if none are implied)."
        )
    elif kind == "story":
        parts.append(
            "Produce the full story: title, description (As a [role], I want [capability], "
            "so that [benefit]), Given/When/Then scenarios, acceptance criteria derived from "
            "those scenarios, and error handling — to the same depth and structure as this "
            "project's other stories."
        )
    elif kind == "scenario":
        parts.append(
            "Produce one Given/When/Then scenario: given states the precondition only (no "
            "actions, no outcomes), when is a single unambiguous trigger — one action, one "
            "input, one event, never \"when X and Y\" — and then is the observable, testable "
            "outcome. One behavior only; if what the PM described has two independent "
            "outcomes, capture the primary one they're describing, not both at once. Do not "
            "duplicate a scenario already listed above."
        )
    elif kind == "error_handling":
        parts.append(
            "Produce one error-handling entry: a short condition label and its message. Use "
            "the PM's own wording for the condition if they gave one; use "
            "`[TBD: exact copy]` for the message unless the PM specified exact wording — do "
            "not invent a plausible-sounding error message. Do not duplicate an entry already "
            "listed above."
        )
    else:
        parts.append(
            "Produce one single, affirmative, testable acceptance criterion sentence that "
            "captures what the PM described — not a bundle of several conditions joined by "
            "\"and\", and not a vague restatement of the subject. Do not duplicate a "
            "criterion already listed above."
        )
    return "".join(parts)


