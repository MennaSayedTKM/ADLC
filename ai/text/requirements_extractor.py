# OpenAI's structured-output JSON has been observed to occasionally
# truncate a `\uXXXX` escape for a smart-punctuation character down to just
# its last two hex digits — confirmed directly: an epic title the model was
# copying verbatim from a source section heading ("4.1 Core Strategy
# Execution Model – Phase 1") came back with a bare U+0013 control
# character (DC3) in place of the en dash (U+2013) — the "20" high byte of
# the escape silently dropped. A raw control character has no glyph in any
# font, so it renders as a tofu/"missing glyph" box in the browser — not
# because the intended character is exotic, but because what actually
# reached the database wasn't a real character at all. Confirmed against a
# real project's data: 8 epic titles, always at a copied section-heading
# dash, always U+0013 (en dash) or U+0014 (em dash). Map covers those two
# plus the equivalent truncation for the smart-quote characters, which are
# generated by the same "quote verbatim" instructions and would suffer the
# identical failure mode even though no case has been observed yet.
_TRUNCATED_UNICODE_ESCAPE_MAP = {
    "\x13": "–",  # en dash –
    "\x14": "—",  # em dash —
    "\x18": "‘",  # left single quote '
    "\x19": "’",  # right single quote '
    "\x1c": "“",  # left double quote "
    "\x1d": "”",  # right double quote "
}


def _sanitize_text(value: str) -> str:
    for bad, good in _TRUNCATED_UNICODE_ESCAPE_MAP.items():
        value = value.replace(bad, good)
    # Any other stray C0 control character is never legitimate in extracted
    # business text — drop it rather than let a second, unmapped instance
    # of this failure mode reach the database as an unrenderable byte.
    return "".join(ch for ch in value if ch in "\n\t\r" or ord(ch) >= 0x20)


def _sanitize_model_output(obj: Any) -> Any:
    """Recursively applies _sanitize_text to every string in a parsed JSON tool-call result."""
    if isinstance(obj, str):
        return _sanitize_text(obj)
    if isinstance(obj, list):
        return [_sanitize_model_output(v) for v in obj]
    if isinstance(obj, dict):
        return {k: _sanitize_model_output(v) for k, v in obj.items()}
    return obj


