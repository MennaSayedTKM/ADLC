_MAX_GRANULARITY_REPAIR_ATTEMPTS = 2


def _looks_already_well_split(data: dict[str, Any]) -> bool:
    """
    Cheap, zero-latency heuristic deciding whether the granularity audit
    call is even worth running: if every epic already has 2+ stories, the
    exact failure signature that audit exists to catch — an epic collapsed
    to exactly 1 story regardless of how many independently-shippable
    bullets its source subsection actually has, confirmed repeatedly, live,
    against a real SOW — cannot be present, so there is nothing for the
    audit to find. Skipping in that case removes one full sequential LLM
    call (plus its own retry-on-malformed-JSON attempts) from the common,
    already-fine case, which was confirmed to be a meaningful chunk of
    upload latency. Any epic still sitting at exactly 1 story is exactly
    the ambiguous case only the audit can actually resolve (a genuinely
    single-bullet epic vs. a missed split) — the audit still runs whenever
    that's true for even one epic, so this never trades away the
    reliability fix, only the wasted call when it plainly isn't needed.
    """
    story_counts: dict[str, int] = {}
    for story in data["user_stories"]:
        story_counts[story["epic_id"]] = story_counts.get(story["epic_id"], 0) + 1
    return all(story_counts.get(epic["id"], 0) >= 2 for epic in data["epics"])


def _ensure_story_granularity(
    source_text: str,
    data: dict[str, Any],
    client,
    model: str,
    existing_epic_ids: Optional[set[str]] = None,
    extra_context: str = "",
) -> tuple[dict[str, Any], list[Usage]]:
    """
    Dedicated audit + narrow repair for one specific, recurring failure mode:
    a broad review pass juggling many instructions at once (confirmed
    repeatedly, live, against a real SOW) reliably under-splits epics whose
    source subsection has several independently-shippable bullets, even with
    an explicit STORY GRANULARITY rule and worked example in its context —
    the same reliability gap, one level up, that motivated splitting empty-
    epic repair out of the review pass in the first place (see
    _ensure_nonempty_epics). A dedicated audit call whose only job is
    counting source bullets against existing stories, followed by a repair
    call whose only job is adding the missing sibling stories, is far more
    reliable at this one narrow thing than hoping the general review pass
    gets it right via prose instructions alone. See
    _looks_already_well_split for the cheap pre-check that skips the audit
    call entirely when there's no signal it could find anything.
    """
    usages: list[Usage] = []
    if _looks_already_well_split(data):
        return data, usages
    for _ in range(_MAX_GRANULARITY_REPAIR_ATTEMPTS):
        findings, audit_usage = _call_granularity_audit(
            source_text, data, client, model, extra_context=extra_context
        )
        usages.append(audit_usage)
        under_split = [f for f in findings if f.get("under_split") and f.get("missing_capabilities")]
        if not under_split:
            break
        data, repair_usage = _repair_undersplit_epics(
            source_text, data, under_split, client, model, extra_context=extra_context
        )
        validate_extraction(data, existing_epic_ids=existing_epic_ids)
        usages.append(repair_usage)
    return data, usages


_GAP_WORTHY_AUDIT_LABELS = ("MISMATCHED DOMAIN", "NEEDS PM DECISION")


def _count_gap_worthy_audit_findings(coverage_audit: str) -> int:
    """
    Rough, robust-by-construction lower bound on how many gaps the final
    extraction must contain — a simple substring count of the coverage
    audit's own required labels, rather than parsing the audit's free-text
    structure. The audit is deliberately unstructured prose (reasoning out
    loud catches more than a tool-call self-check would), so its exact
    formatting isn't guaranteed run to run, but COVERAGE_AUDIT_SYSTEM_PROMPT
    requires these two label strings verbatim on every qualifying line,
    which a plain count survives regardless of surrounding formatting. This
    count only decides WHETHER to fire a repair call; the repair call itself
    re-reads the full audit text to work out exactly which findings are
    still missing a gap, so a rough count is enough here.
    """
    return sum(coverage_audit.count(label) for label in _GAP_WORTHY_AUDIT_LABELS)


