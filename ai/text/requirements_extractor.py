def generate_clarifying_questions(
    combined_resource_text: str,
    client,
    model: str = EXTRACTION_MODEL,
) -> tuple[list[dict[str, str]], Usage]:
    """
    Reads everything staged for a project so far (see
    backend/app/services/intake_resources.py) and proposes plain-language
    questions a PM can relay to a non-technical stakeholder to fill real
    gaps before extraction runs. Like generate_suggestions(), this is
    advisory bonus content, not the primary deliverable — an empty list is
    a valid, expected result when the staged material is already thorough.

    Two separate calls, not one: the material-specific gap call above, and
    _call_baseline_categories_audit — a fixed-checklist coverage check with
    no other job. Confirmed directly that combining both into a single
    call's instructions caused the model to reliably skip the checklist
    check whenever it found enough material-specific gaps on its own; see
    BASELINE_CATEGORIES_AUDIT_SYSTEM_PROMPT's docstring-comment for the full
    story. Costs 2x one call, the same tradeoff extract_requirements()
    already makes for coverage reliability elsewhere in this pipeline.
    """
