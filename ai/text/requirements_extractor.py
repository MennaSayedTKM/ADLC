def generate_item_draft(
    kind: str,
    subject: str,
    client,
    model: str = EXTRACTION_MODEL,
    project_context: str = "",
    parent_context: str = "",
    previous_draft: Optional[dict] = None,
) -> tuple[dict[str, Any], Usage]:
    """
    PM-initiated, single-item AI-assisted generation — the PM names a
    subject for one epic, story, acceptance criterion, scenario, or
    error-handling entry and this fleshes it out to the same
    structure/rigor as the rest of the extraction. The result is a DRAFT
    only: nothing is persisted here, the caller shows it to the PM to
    confirm (or discard) before it's saved, same as every other AI output
    in this system being advisory rather than auto-committed.

    Pass `previous_draft` (whatever this function returned last time, for
    the same subject) when the PM clicked Regenerate rather than Add —
    temperature is raised for that call and the previous draft is given to
    the model with an explicit instruction to differ from it, since at the
    default temperature=0 a plain re-roll of the same subject tends to
    reproduce the same draft the PM just rejected.
    """
    if kind not in _DRAFT_TOOLS:
        raise ValueError(
            f"Invalid kind: {kind!r} — expected 'epic', 'story', 'acceptance_criterion', "
            "'scenario', or 'error_handling'"
        )
    tool, tool_name = _DRAFT_TOOLS[kind]
    prompt = _build_generate_item_prompt(kind, subject, project_context, parent_context, previous_draft)
    temperature = 0.9 if previous_draft else 0
    data, usage = _call_with_tool(GENERATE_ITEM_SYSTEM_PROMPT, prompt, client, model, tool, tool_name, temperature)

    if kind == "acceptance_criterion":
        if "text" not in data or not isinstance(data["text"], str):
            raise ValueError(f"Malformed acceptance criterion draft: {data!r}")
        data = {"text": data["text"], "out_of_scope": False}
    elif kind == "epic":
        for key in ("title", "assumptions", "dependencies"):
            if key not in data:
                raise ValueError(f"Malformed epic draft, missing {key!r}: {data!r}")
    elif kind == "story":
        required = ("title", "description", "scenarios", "acceptance_criteria", "error_handling")
        if any(key not in data for key in required):
            raise ValueError(f"Malformed story draft: {data!r}")
    elif kind == "scenario":
        required = ("title", "given", "when", "then")
        if any(key not in data for key in required):
            raise ValueError(f"Malformed scenario draft: {data!r}")
        data = {**data, "source_reference": ""}
    else:  # error_handling
        required = ("condition", "message")
        if any(key not in data for key in required):
            raise ValueError(f"Malformed error handling draft: {data!r}")

    return data, usage


