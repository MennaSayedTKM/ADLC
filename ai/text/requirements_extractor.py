_MAX_REPAIR_ATTEMPTS = 2


def _ensure_nonempty_epics(
    source_text: str,
    data: dict[str, Any],
    client,
    model: str,
    existing_epic_ids: Optional[set[str]] = None,
    extra_context: str = "",
) -> tuple[dict[str, Any], list[Usage]]:
    """
    Runs _repair_empty_epics up to _MAX_REPAIR_ATTEMPTS times, stopping as
    soon as no epic this response declared is left with zero stories.
    Confirmed via repeated live testing against a real SOW: a single repair
    call sometimes still leaves an epic unresolved even with an explicit
    self-check instruction in its own prompt (the same reliability gap that
    motivated splitting repair out of the broader review pass in the first
    place, just recurring one level down). A bounded retry is a cheap,
    purely mechanical improvement on top of the prompt itself — each repair
    call is narrow and small relative to the full review pass, so a second
    attempt costs little.
    """
    usages: list[Usage] = []
    for _ in range(_MAX_REPAIR_ATTEMPTS):
        empty_epics = _empty_new_epics(data, {e["id"] for e in data["epics"]})
        if not empty_epics:
            break
        data, repair_usage = _repair_empty_epics(
            source_text, data, empty_epics, client, model, extra_context=extra_context
        )
        validate_extraction(data, existing_epic_ids=existing_epic_ids)
        usages.append(repair_usage)
    return data, usages


