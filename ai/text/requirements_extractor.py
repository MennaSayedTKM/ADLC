_MAX_MALFORMED_RESPONSE_ATTEMPTS = 3


def _create_and_parse_tool_call(make_request, tool_name: str) -> tuple[dict[str, Any], Usage]:
    """
    Calls make_request() (a zero-arg callable returning a raw OpenAI
    ChatCompletion response) and parses the named tool call's JSON
    arguments, retrying the whole request up to
    _MAX_MALFORMED_RESPONSE_ATTEMPTS times if the model's response is
    missing the tool call entirely or comes back as malformed/truncated
    JSON. Confirmed to happen intermittently even at temperature=0 — a live
    CR upload failed this way twice in a row with two different symptoms
    (a truncated JSON string, then a different unhandled error), while an
    otherwise-identical direct reproduction of the same request succeeded
    immediately after. This is the same class of non-determinism already
    documented elsewhere in this file (see _call_llm's temperature
    comment), just surfacing as a malformed response instead of an
    inconsistent-but-valid one — so absorb it with a retry here rather than
    failing the whole PM-facing request on one bad response.
    """
    last_error: Optional[Exception] = None
    for _ in range(_MAX_MALFORMED_RESPONSE_ATTEMPTS):
        response = make_request()
        tool_calls = response.choices[0].message.tool_calls or []
        tool_call = next((tc for tc in tool_calls if tc.function.name == tool_name), None)
        if tool_call is None:
            last_error = ValueError(f"Model did not return a tool call with the {tool_name} result.")
            continue
        try:
            data = _sanitize_model_output(json.loads(tool_call.function.arguments))
        except json.JSONDecodeError as e:
            last_error = e
            continue
        usage = Usage(
            prompt_tokens=response.usage.prompt_tokens,
            completion_tokens=response.usage.completion_tokens,
        )
        return data, usage
    raise ValueError(
        f"Model's {tool_name} response was malformed after "
        f"{_MAX_MALFORMED_RESPONSE_ATTEMPTS} attempts: {last_error}"
    ) from last_error


def _call_llm(system_prompt: str, prompt: str, client, model: str) -> tuple[dict[str, Any], Usage]:
    def make_request():
        return client.chat.completions.create(
            model=model,
            max_tokens=EXTRACTION_MAX_TOKENS,
            # Default temperature (~1.0) produced wildly different output
            # volume for the same input in testing (896 vs. 3387 completion
            # tokens, 2 vs. 6 stories); 0.2 was still inconsistent (959 vs.
            # 1726 tokens). This is a structured extraction task, not a
            # creative one — minimize sampling variance rather than trade
            # consistency for it.
            temperature=0,
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": prompt},
            ],
            tools=[_EXTRACTION_TOOL],
            tool_choice={"type": "function", "function": {"name": "record_extraction"}},
        )

    return _create_and_parse_tool_call(make_request, "record_extraction")


def _call_with_tool(
    system_prompt: str, prompt: str, client, model: str, tool: dict, tool_name: str, temperature: float = 0
) -> tuple[dict[str, Any], Usage]:
    """
    Same shape as _call_llm above, generalized to an arbitrary tool/schema —
    used by the single-item draft generators below, which each need a
    smaller, kind-specific schema (just a story, just an epic, just one
    acceptance criterion) rather than the full epics/user_stories/gaps one.
    _call_llm itself is left untouched rather than rewritten in terms of
    this, to avoid any behavioral risk to the well-tested main pipeline for
    a refactor that's purely about not duplicating this one more time —
    both instead share the retry-on-malformed-response logic via
    _create_and_parse_tool_call.

    temperature defaults to 0 (consistency) but generate_item_draft raises
    it for a PM-requested regeneration, where the whole point is to get a
    genuinely different result from the same subject — 0 would otherwise
    make "Regenerate" reproduce the same draft the PM already rejected.
    """

    def make_request():
        return client.chat.completions.create(
            model=model,
            max_tokens=EXTRACTION_MAX_TOKENS,
            temperature=temperature,
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": prompt},
            ],
            tools=[tool],
            tool_choice={"type": "function", "function": {"name": tool_name}},
        )

    return _create_and_parse_tool_call(make_request, tool_name)


