def _call_coverage_audit(source_text: str, draft: dict[str, Any], client, model: str) -> tuple[str, Usage]:
    """
    Plain-text reasoning pass, not a tool call — asking the model to reason
    out loud about coverage before the final structured fix tends to surface
    more than asking a tool-call to silently self-check would. The output
    isn't parsed, just fed as context into the review call below.
    """
    response = client.chat.completions.create(
        model=model,
        max_tokens=EXTRACTION_MAX_TOKENS,
        temperature=0,
        messages=[
            {"role": "system", "content": COVERAGE_AUDIT_SYSTEM_PROMPT},
            {"role": "user", "content": _build_coverage_audit_prompt(source_text, draft)},
        ],
    )
    text = response.choices[0].message.content or ""
    usage = Usage(
        prompt_tokens=response.usage.prompt_tokens,
        completion_tokens=response.usage.completion_tokens,
    )
    return text, usage


