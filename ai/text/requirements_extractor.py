"""
requirements_extractor.py
Text-based structured requirements extraction via OpenAI (function-calling,
for enforced structured output — not the fragile JSON-in-text parsing
ai/vision/alignment_checker.py uses) — replaces the old vision-based GPT-4o
extractor (deleted; this is a text-extraction task, not a visual one, so no
vision model and no embeddings are involved anywhere in this path).

Was on Claude (tool-use) originally; switched to OpenAI for now (matching the
provider already used for design alignment) — see _call_llm() below. Swapping
back only needs a new _call_llm() implementation; extract_requirements(),
extract_change_request(), and validate_extraction() are provider-agnostic.

Two entry points sharing the same schema and validation:
  - extract_requirements(): a fresh document (e.g. a new-project SOW) with no
    existing baseline — every epic is new.
  - extract_change_request(): a CR filed against a project that already has
    an approved requirements baseline. The model sees that baseline's epics
    and decides, per story, whether it extends an existing epic (reusing its
    id) or introduces a genuinely new one — CRs shouldn't silently duplicate
    epics that already exist.

Output depth follows a GROUNDED FACTS vs PROFESSIONAL ELABORATION split (see
SYSTEM_PROMPT), not a literal-detail-only rule: standard implementation
mechanics implied by a capability's own verb ("configure" implies create/
edit/view; a named responsible role implies an unauthorized-access negative
case) are written even when the source describes no screen — that's what a
working BA does, not fabrication. What's never invented is anything
specific the source doesn't give: named entities/fields/systems, exact
numbers or thresholds, or literal UI/error copy.

Each entry point is three model calls, plus a conditional fourth: a
first-draft extraction (_call_llm with SYSTEM_PROMPT), a plain-text coverage
audit that checks the draft against every subsection of the source
(_call_coverage_audit — reasoning out loud catches more than a tool-call
silently self-checking would), a review pass (_call_llm with
REVIEW_SYSTEM_PROMPT) that fixes whatever the audit found plus the usual
correctness checks, and — only if the review pass still leaves an epic with
zero stories — a narrow repair call (_repair_empty_epics) whose only job is
fixing exactly those epics. This exists because a real run silently dropped
a whole mandatory capability section with no signal anywhere in the output
— confirmed directly against a real SOW — and the two-call (draft + review)
design didn't catch it either, since the review pass only re-checks the
draft's own claims, not the source's full inventory of requirements. Once
the coverage audit was strong enough to catch that, a second problem
surfaced just as reliably: MIRROR SOURCE STRUCTURE creates an epic per
source subsection before the model knows whether that subsection is
story-worthy, and the review pass — despite an explicit instruction to
delete any leftover empty shell — kept leaving out-of-scope subsections'
epics in place empty rather than deleting them. The repair call exists
because that specific, narrow fix proved unreliable when it was just one
instruction among many in a broad review pass, but is far more reliable as
a call with no other job.
"""

