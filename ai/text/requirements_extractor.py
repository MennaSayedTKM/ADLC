def _renumber_colliding_ids(data: dict[str, Any], existing_epic_ids: set[str]) -> dict[str, Any]:
    """
    The suggestions prompt tells the model not to reuse an existing epic id
    when it introduces a new one, and to keep its own story ids unique —
    but, like every other "just don't do X" instruction relied on alone
    this session, that isn't reliable enough on its own: confirmed
    directly against a real project, a suggestions call proposed a new
    epic as "E1", colliding with the project's actual existing E1, which
    made validate_extraction() reject the whole batch and — since a
    suggestions failure is swallowed rather than retried, being advisory
    content the PM never asked for — silently produced zero suggestions
    with no visible error anywhere. Fixed deterministically here instead
    of trusting the prompt further: any new epic id colliding with an
    existing one (or with another new epic in the same batch) is
    reassigned to the next free "E{n}" slot, with every story's epic_id
    reference updated to match; any duplicate story id within the batch is
    likewise reassigned to the next free "S{n}" slot.
    """
    taken_epics = set(existing_epic_ids)
    epic_id_map: dict[str, str] = {}
    next_epic_n = 1

    def next_free_epic_id() -> str:
        nonlocal next_epic_n
        while f"E{next_epic_n}" in taken_epics:
            next_epic_n += 1
        taken_epics.add(f"E{next_epic_n}")
        return f"E{next_epic_n}"

    for epic in data["epics"]:
        old_id = epic["id"]
        if old_id in taken_epics:
            new_id = next_free_epic_id()
            epic_id_map[old_id] = new_id
            epic["id"] = new_id
        else:
            taken_epics.add(old_id)

    taken_stories: set[str] = set()
    next_story_n = 1

    def next_free_story_id() -> str:
        nonlocal next_story_n
        while f"S{next_story_n}" in taken_stories:
            next_story_n += 1
        taken_stories.add(f"S{next_story_n}")
        return f"S{next_story_n}"

    for story in data["user_stories"]:
        if story["epic_id"] in epic_id_map:
            story["epic_id"] = epic_id_map[story["epic_id"]]
        if story["id"] in taken_stories:
            story["id"] = next_free_story_id()
        else:
            taken_stories.add(story["id"])

    return data


def generate_suggestions(
    source_text: str,
    final_data: dict[str, Any],
    client,
    model: str = EXTRACTION_MODEL,
    reserved_epic_ids: Optional[set[str]] = None,
) -> tuple[dict[str, Any], Usage]:
    """
    Runs automatically right after a fresh extraction's review pass, using
    the SAME tool/schema as the main extraction (epics/user_stories/gaps) so
    existing plumbing and test fixtures don't need a second schema to know
    about — gaps is just unused here. Unlike the main extraction, a failure
    or a low-quality result here is not worth another model call to fix:
    this is advisory bonus content the PM never asked for, so validation is
    lenient and any epic that still ends up empty is silently dropped in
    code rather than repaired.

    reserved_epic_ids covers epic ids that are already occupied in the
    database but deliberately excluded from final_data["epics"] — a still-
    pending (not yet accepted/dismissed) suggestion from an earlier run,
    for instance. final_data excludes those from the PROMPT on purpose (an
    unconfirmed suggestion shouldn't count as "already covered" when this
    call decides what's genuinely missing), but that same content-visibility
    filter must not also hide the id from collision detection — confirmed
    directly: a still-pending "E9" suggestion from an earlier run wasn't in
    final_data, so a new suggestions batch reusing "E9" sailed past both
    _renumber_colliding_ids and validate_extraction (both keyed off the same
    epics-derived set) and only failed all the way down at the database's
    own UNIQUE constraint. Callers must pass every external_id currently
    persisted for the document, regardless of suggestion_status.
    """
    existing_epics = [ExistingEpic(external_id=e["id"], title=e["title"]) for e in final_data["epics"]]
    prompt = _build_suggestions_prompt(source_text, final_data, existing_epics)
    data, usage = _call_llm(SUGGESTIONS_SYSTEM_PROMPT, prompt, client, model)

    existing_epic_ids = {e.external_id for e in existing_epics} | (reserved_epic_ids or set())
    data = _renumber_colliding_ids(data, existing_epic_ids)
    validate_extraction(data, existing_epic_ids=existing_epic_ids)

    empty = _empty_new_epics(data, {e["id"] for e in data["epics"]})
    if empty:
        data["epics"] = [e for e in data["epics"] if e["id"] not in empty]

    return data, usage


